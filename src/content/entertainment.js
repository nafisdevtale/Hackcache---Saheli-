export function getEntertainmentById(id) {
  if (!id) return undefined;
  return VERIFIED_ENTERTAINMENT.find((m) => m.id === id || m.providerId === id);
}

export function filterEntertainmentByType(type = "all") {
  if (!type || type === "all") return [...VERIFIED_ENTERTAINMENT];
  return VERIFIED_ENTERTAINMENT.filter((m) => m.type === type);
}
