import { describe, test, expect, beforeEach } from "vitest";
import fs from "node:fs";
import path from "node:path";
import enDict from "../i18n/en.js";
import {
  exportCSV,
  parseCSVImport,
  exportJSON,
  parseImport,
  parsePDFImport,
  importPreview,
  mergeRecords,
  emptyRecord,
  blankDay,
} from "../lib/exportImport.js";
import { generateClinicalSummaryPDF } from "../lib/pdfGenerator.ts";
import {
  handleFeedbackRequest,
  resetFeedbackStore,
  reloadFeedbackStoreFromDisk,
} from "../server/api/feedback.ts";
import { loadFeedbackDraft, saveFeedbackDraft, exportReportAsText } from "../lib/feedbackClient.js";

// Ensure mock localStorage is available in test environment
const lsStore = new Map<string, string>();
const mockLocalStorage = {
  getItem: (k: string) => (lsStore.has(k) ? lsStore.get(k)! : null),
  setItem: (k: string, v: string) => lsStore.set(k, String(v)),
  removeItem: (k: string) => lsStore.delete(k),
  clear: () => lsStore.clear(),
};
Object.defineProperty(globalThis, "localStorage", {
  value: mockLocalStorage,
  writable: true,
  configurable: true,
});

describe("SAHELI 11.7 — Fix The Running App", () => {
  beforeEach(() => {
    lsStore.clear();
    resetFeedbackStore(true);
  });

  describe("1. Multi-Format Ingestion & Signature Detection (JSON, CSV, PDF)", () => {
    test("detects and parses JSON backups cleanly", () => {
      const rec = emptyRecord();
      rec.days["2026-03-01"] = { ...blankDay("2026-03-01"), period: true, flow: "medium", pain: 2 };
      rec.days["2026-03-02"] = { ...blankDay("2026-03-02"), period: true, flow: "heavy", pain: 3 };

      const jsonStr = exportJSON(rec);
      const res = parseImport(jsonStr);
      expect(res.ok).toBe(true);
      if (res.ok) {
        expect(Object.keys(res.record.days)).toHaveLength(2);
        expect(res.record.days["2026-03-01"].flow).toBe("medium");
      }
    });

    test("detects and parses CSV exports with ovulation & symptom metadata", () => {
      const rec = emptyRecord();
      rec.days["2026-03-10"] = {
        ...blankDay("2026-03-10"),
        period: true,
        flow: "heavy",
        pain: 3,
        symptoms: ["cramps", "headache"],
      };

      const csvStr = exportCSV(rec);
      expect(csvStr.toLowerCase()).toContain("date,period,flow,padhourly");

      const res = parseCSVImport(csvStr);
      expect(res.ok).toBe(true);
      if (res.ok) {
        expect(res.record.days["2026-03-10"]).toBeDefined();
        expect(res.record.days["2026-03-10"].period).toBe(true);
        expect(res.record.days["2026-03-10"].flow).toBe("heavy");
        expect(res.record.days["2026-03-10"].symptoms).toContain("cramps");
      }
    });

    test("detects and extracts lossless payload from binary PDF generated by Saheli", async () => {
      const rec = emptyRecord();
      rec.days["2026-03-15"] = {
        ...blankDay("2026-03-15"),
        period: true,
        flow: "medium",
        pain: 1,
        symptoms: ["bloating"],
      };

      const pdfBytes = generateClinicalSummaryPDF(rec, { cycles: [], stats: { meanLength: 28 } });
      expect(ArrayBuffer.isView(pdfBytes) || (pdfBytes && "byteLength" in (pdfBytes as any))).toBe(
        true,
      );

      // Pass Uint8Array directly
      const res1 = parsePDFImport(pdfBytes);
      expect(res1.ok).toBe(true);
      if (res1.ok) {
        expect(res1.record.days["2026-03-15"].symptoms).toContain("bloating");
      }

      // Pass ArrayBuffer directly
      const res2 = parsePDFImport(pdfBytes.buffer);
      expect(res2.ok).toBe(true);
      if (res2.ok) {
        expect(res2.record.days["2026-03-15"].flow).toBe("medium");
      }
    });

    test("accurately calculates import preview with conflicts and fresh entries", () => {
      const existing = emptyRecord();
      existing.days["2026-03-01"] = blankDay("2026-03-01");
      existing.days["2026-03-02"] = blankDay("2026-03-02");

      const incoming = emptyRecord();
      incoming.days["2026-03-02"] = blankDay("2026-03-02"); // Conflict
      incoming.days["2026-03-03"] = blankDay("2026-03-03"); // Fresh
      incoming.days["2026-03-04"] = blankDay("2026-03-04"); // Fresh

      const preview = importPreview(existing, incoming);
      expect(preview.total).toBe(3);
      expect(preview.conflicts).toBe(1);
      expect(preview.fresh).toBe(2);

      // Verify merge strategy preserves existing conflict record
      existing.days["2026-03-02"].note = "Original Note";
      incoming.days["2026-03-02"].note = "Overwritten Note";

      const merged = mergeRecords(existing, incoming, "merge");
      expect(merged.days["2026-03-02"].note).toBe("Original Note");
      expect(merged.days["2026-03-03"]).toBeDefined();

      // Verify replace strategy overrides existing
      const replaced = mergeRecords(existing, incoming, "replace");
      expect(replaced.days["2026-03-02"].note).toBe("Overwritten Note");
      expect(replaced.days["2026-03-01"]).toBeUndefined();
    });
  });

  describe("2. Durable Feedback Submission End-to-End", () => {
    test("submits feedback, persists to disk, and survives server restart", async () => {
      const payload = {
        consent: true,
        category: "bug",
        title: "Test UI Glitch in Settings",
        description: "Encountered a glitch when switching tabs under high contrast mode.",
        severity: "medium",
        stepsToReproduce: "1. Go to Settings\n2. Toggle high contrast\n3. Switch tabs",
      };

      const req = new Request("http://localhost/api/feedback", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });

      const res = await handleFeedbackRequest(req);
      expect(res.status).toBe(200);
      const data = await res.json();
      expect(data.ok).toBe(true);
      expect(data.reportId).toMatch(/^REP-/);

      // Verify persistence to .data/feedback_reports.json on disk
      const storageFile = path.resolve(process.cwd(), ".data/feedback_reports.json");
      expect(fs.existsSync(storageFile)).toBe(true);
      const rawDiskData = fs.readFileSync(storageFile, "utf-8");
      expect(rawDiskData).toContain(data.reportId);
      expect(rawDiskData).toContain("Test UI Glitch in Settings");

      // Simulate complete server restart by reloading store from disk
      const freshStore = reloadFeedbackStoreFromDisk();
      expect(freshStore.has(data.reportId)).toBe(true);

      // Verify retrieval through maintainer review endpoint
      const maintainerReq = new Request("http://localhost/api/feedback/reports", {
        method: "GET",
        headers: {
          "x-maintainer-key": "saheli-dev-maintainer-key-2026",
        },
      });

      const maintainerRes = await handleFeedbackRequest(maintainerReq);
      expect(maintainerRes.status).toBe(200);
      const maintainerData = await maintainerRes.json();
      expect(maintainerData.ok).toBe(true);
      expect(maintainerData.count).toBeGreaterThanOrEqual(1);
      const found = maintainerData.reports.find((r: any) => r.id === data.reportId);
      expect(found).toBeDefined();
      expect(found.title).toBe("Test UI Glitch in Settings");
    });

    test("client preserves unsent draft and allows offline text export if transmission fails", async () => {
      const draft = {
        category: "translation",
        title: "Missing Marathi string in Export summary",
        description: "The summary doc header does not translate when Marathi is selected.",
        consent: true,
      };

      saveFeedbackDraft(draft);
      const loaded = loadFeedbackDraft();
      expect(loaded.title).toBe(draft.title);

      const exportedText = exportReportAsText(draft);
      expect(exportedText).toContain("=== SAHELI BUG REPORT & FEEDBACK ===");
      expect(exportedText).toContain("Missing Marathi string in Export summary");
      expect(exportedText).toContain("PRIVACY CERTIFICATION");
    });
  });

  describe("3. App Lock & Vault Security Architecture", () => {
    test("vault status strings and user disclosures remain free of cryptographic jargon", () => {
      // User-facing explanations must be plain and reassuring
      expect(enDict["vault.storageStatus"]).toBe(
        "Your saved records are encrypted on this device.",
      );
      expect(enDict["vault.appLockStatus"]).toBe("Choose how to unlock Saheli.");
      expect(enDict["vault.accessExplanation"]).toBe(
        "The encrypted vault is Saheli's protected local storage for your personal records. It is not a separate account and does not require an online login.",
      );

      // Verify no confusing internal jargon leaked into user-facing copy
      expect(enDict["vault.accessExplanation"]).not.toContain("DEK");
      expect(enDict["vault.accessExplanation"]).not.toContain("KEK");
      expect(enDict["vault.accessExplanation"]).not.toContain("CryptoKey");
      expect(enDict["vault.accessExplanation"]).not.toContain("PBKDF2");
    });
  });
});
