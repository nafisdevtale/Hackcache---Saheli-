const languages = ["en", "hi", "mr", "te", "kn", "ta", "bn", "gu", "pa", "ml", "or", "as", "ur"];

for (const lang of languages) {
  const filePath = path.join(i18nDir, `${lang}.js`);
  let content = fs.readFileSync(filePath, "utf-8");

  for (const [key, transObj] of Object.entries(NEW_KEYS)) {
    const val = transObj[lang] || transObj["en"];
    const escapedVal = val.replace(/"/g, '\\"');

    // Check if key already present
    if (!content.includes(`"${key}":`)) {
      const insertion = `  "${key}": "${escapedVal}",\n`;
      content = content.replace("export default {\n", `export default {\n${insertion}`);
    }
  }

  fs.writeFileSync(filePath, content, "utf-8");
  console.log(`Updated [${lang}] with INSTINCT translation keys.`);
}
