for (const lang of LANGUAGES) {
  const code = lang.code;
  const filePath = path.join(i18nDir, `${code}.js`);
  if (!fs.existsSync(filePath)) continue;

  const currentDict = { ...DICTS[code] };
  const newKeys = TRACKER_TRANSLATIONS[code] || TRACKER_TRANSLATIONS.en;

  for (const [k, v] of Object.entries(newKeys)) {
    currentDict[k] = v;
  }

  const sortedKeys = Object.keys(currentDict).sort();
  const lines = ["export default {"];
  for (const k of sortedKeys) {
    const val = currentDict[k];
    const escaped = val.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
    lines.push(`  "${k}": "${escaped}",`);
  }
  lines.push("};");
  lines.push("");

  fs.writeFileSync(filePath, lines.join("\n"), "utf8");
  console.log(`Updated [${code}] with tracker keys (${sortedKeys.length} total keys).`);
}
