    if not os.path.exists(filepath):
        print(f"File not found: {filepath}")
        continue

    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    # The file exports default { ... };
    # We want to add new keys to the exported object
    new_keys = DATA[lang]
    # Check what keys are already present
    added_count = 0
    lines_to_add = []
    for k, v in new_keys.items():
        escaped_val = json.dumps(v, ensure_ascii=False)
        # Check if key already in file
        if f'"{k}":' in content or f"'{k}':" in content:
            continue
        lines_to_add.append(f'  "{k}": {escaped_val},')
        added_count += 1

    if added_count > 0:
        # Find the last closing brace before semicolon or EOF
        idx = content.rfind("};")
        if idx == -1:
            idx = content.rfind("}")
        
        insert_block = "\n" + "\n".join(lines_to_add) + "\n"
        new_content = content[:idx] + insert_block + content[idx:]
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(new_content)
        print(f"[{lang}] Added {added_count} new translation keys.")
    else:
        print(f"[{lang}] All keys already present.")

